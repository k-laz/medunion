// Writes public/admin/config.yml (the site editor's settings) from
// public/admin/config.template.yml, filling its drop-down lists from the site's
// own files: price names per city, doctors per city, and the service sections a
// new service can go in. Runs before every build, so a doctor or price added at
// /admin/ shows up in these lists after the next build.
//   node scripts/admin-config.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join, relative } from 'node:path';
import { parse, parseDocument } from 'yaml';

async function walk(d, ext) {
  if (!existsSync(d)) return [];
  const out = [];
  for (const e of await readdir(d, { withFileTypes: true })) {
    const p = join(d, e.name);
    if (e.isDirectory()) out.push(...(await walk(p, ext)));
    else if (e.name.endsWith(ext)) out.push(p);
  }
  return out;
}
const front = async (f) => parse((await readFile(f, 'utf8')).match(/^---\n([\s\S]*?)\n---/)?.[1] ?? '') ?? {};

async function prices(dir) {
  const out = [];
  for (const f of (await walk(dir, '.yml')).sort()) {
    const d = parse(await readFile(f, 'utf8')) ?? {};
    for (const it of d.items ?? []) if (it?.name) out.push({ label: `${it.name} · ${Number(it.price).toLocaleString('ru-RU')} ₽ (${d.title})`, value: String(it.name) });
  }
  return [...new Map(out.map((o) => [o.value, o])).values()];
}
async function doctors(dir) {
  const out = [];
  for (const f of await walk(dir, '.md')) {
    const d = await front(f);
    if (!d.name || d.hidden) continue;
    out.push({ label: `${d.name} · ${d.specialty ?? ''}`, value: relative(dir, f).replace(/\.md$/, '') });
  }
  return out.sort((a, b) => a.label.localeCompare(b.label, 'ru'));
}
async function sections(dir) {
  const all = [];
  for (const f of await walk(dir, '.md')) {
    const d = await front(f);
    if (d.url && !d.hidden) all.push({ url: String(d.url), h1: String(d.h1 ?? d.url) });
  }
  return all
    .filter((s) => s.url === '/uslugi/' || all.some((o) => o.url !== s.url && o.url.startsWith(s.url)))
    .sort((a, b) => a.url.localeCompare(b.url))
    .map((s) => ({ label: `${'· '.repeat(s.url.split('/').filter(Boolean).length - 1)}${s.h1}`, value: s.url }));
}

const lists = {
  __PRICES_KRASNOYARSK__: await prices('src/data/prices'),
  __PRICES_KANSK__: await prices('src/data/prices-kansk'),
  __DOCTORS_KRASNOYARSK__: await doctors('src/content/doctors'),
  __DOCTORS_KANSK__: await doctors('src/content-kansk/doctors'),
  // Reviews: doctors of both cities, each once
  __DOCTORS_ALL__: [...new Map([...(await doctors('src/content/doctors')), ...(await doctors('src/content-kansk/doctors'))].map((o) => [o.value, o])).values()],
  __SECTIONS_KRASNOYARSK__: await sections('src/content/services'),
  __SECTIONS_KANSK__: await sections('src/content-kansk/services'),
};

const doc = parseDocument(await readFile('public/admin/config.template.yml', 'utf8'));
let filled = 0;
const fill = (node) => {
  if (!node || typeof node !== 'object') return;
  for (const item of node.items ?? []) {
    const v = item.value ?? item;
    if (v && typeof v.value === 'string' && lists[v.value]) { item.value = doc.createNode(lists[v.value]); filled++; }
    else fill(v);
  }
};
fill(doc.contents);
const left = JSON.stringify(doc.toJS()).match(/__[A-Z_]+__/);
if (left) throw new Error(`admin-config: ${left[0]} has no list`);
await writeFile('public/admin/config.yml', `# GENERATED by scripts/admin-config.mjs from config.template.yml. Do not edit.\n${doc}`);
console.log(`Admin config: ${filled} lists filled (${Object.entries(lists).map(([k, v]) => `${k.replace(/_/g, '').toLowerCase()} ${v.length}`).join(', ')})`);
